"""
The wire contract between the backend and this worker. Nothing here
touches Postgres. These are the ONLY shapes that cross the queue/
callback boundary — the backend's queue payload builder and callback
receiver should use the same field names (mirror this file, or import it
directly if the backend ever vendors this package).

Replaces the DB-row dataclasses that used to live in db/models.py:
NodeRecord/EdgeRecord/SeedAsset are gone; NodeDraft/EdgeDraft/
SeedAssetDraft below carry the same information but as plain data the
backend inserts, not rows this worker inserts itself.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Any, Literal
from uuid import UUID

from pydantic import BaseModel, Field

DetailLevel = Literal["overview", "balanced", "detailed"]


class JobType(StrEnum):
    GENERATE = "generate"
    REGENERATE_FULL = "regenerate_full"
    REGENERATE_NODE = "regenerate_node"


# ---------------------------------------------------------------------
# Chat intents
# ---------------------------------------------------------------------


class ChatIntent(StrEnum):
    QUESTION = "question"
    EDIT_PROPOSAL = "edit_proposal"
    REGEN_WHOLE = "regen_whole"
    REGEN_NODE = "regen_node"
    SMALL_TALK = "small_talk"


class SeedAssetType(StrEnum):
    PDF = "pdf"
    IMAGE = "image"
    TEXT = "text"


class ChunkSource(StrEnum):
    UPLOADED_SEED = "uploaded_seed"
    WEB_SEARCH = "web_search"
    ARXIV = "arxiv"


# ---------------------------------------------------------------------
# Graph Entities
# ---------------------------------------------------------------------


class NodeDraft(BaseModel):
    id: UUID  # real UUID, generated by the worker at validation time
    label: str
    description: str | None = None
    node_type: str = "default"
    background_color: str | None = None  # "#RRGGBB", validated by validation/schema.py
    text_color: str | None = None
    sources: list[str] = Field(default_factory=list)


class EdgeDraft(BaseModel):
    id: UUID
    source_node_id: UUID
    target_node_id: UUID
    label: str | None = None


class BranchContext(BaseModel):
    nodes: list[NodeDraft] = Field(default_factory=list)
    edges: list[EdgeDraft] = Field(default_factory=list)


# ---------------------------------------------------------------------
# Inbound: backend -> queue -> worker
# ---------------------------------------------------------------------


class FileRef(BaseModel):
    """A file the backend already uploaded to Storage. The worker fetches
    bytes from `url` itself — raw bytes never go through the queue."""

    file_name: str
    mime_type: str
    url: str  # signed URL, short-lived
    storage_key: str  # the real bucket path, e.g. "<user_id>/<map_id>/<job_id>/<file>"


class GenerationRequest(BaseModel):
    job_id: UUID
    map_id: UUID
    job_type: JobType

    # Fresh generation (US-03): topic/ideas/files. At least one of
    # topic/ideas/files must end up producing usable text.
    topic: str | None = None
    ideas: str | None = None
    files: list[FileRef] = Field(default_factory=list)

    # Full regeneration (US-04): the instruction to apply on top of the
    # ORIGINAL seed. The worker reconstructs the seed itself from the
    # vector store (namespace=map_id, source=uploaded_seed) — the
    # backend does not need to resend seed text.
    regeneration_instruction: str | None = None

    # Node-level regeneration (S2-L7):
    # Selected node, attached comment/instruction, branch context, and ancestor labels.
    target_node_id: UUID | None = None
    selected_node: NodeDraft | None = None
    comment: str | None = None
    ancestor_labels: list[str] = Field(default_factory=list)
    branch_context: BranchContext | None = None
    branch_nodes: list[NodeDraft] = Field(default_factory=list)
    branch_edges: list[EdgeDraft] = Field(default_factory=list)

    detail_level: DetailLevel | None = None  # None => worker infers it
    purpose: str | None = None
    seed_has_files: bool = False

    # Internal callback auth — see callback/client.py. Not a user secret;
    # scoped to this one job by the backend when it enqueues.
    callback_base_url: str
    callback_token: str

    @property
    def effective_branch_nodes(self) -> list[NodeDraft]:
        if self.branch_context and self.branch_context.nodes:
            return self.branch_context.nodes
        return self.branch_nodes

    @property
    def effective_branch_edges(self) -> list[EdgeDraft]:
        if self.branch_context and self.branch_context.edges:
            return self.branch_context.edges
        return self.branch_edges

    @property
    def effective_comment(self) -> str | None:
        return self.comment or self.regeneration_instruction


# ---------------------------------------------------------------------
# Outbound: worker -> callback -> backend
# ---------------------------------------------------------------------


class SeedAssetDraft(BaseModel):
    """What the backend needs to insert its own seed_assets row. The
    worker does the extraction (DR-02: parsing stays distinct per type)
    but never writes the row itself."""

    asset_type: SeedAssetType
    file_name: str | None
    storage_key: str | None
    mime_type: str | None
    content_text: str | None
    file_size_bytes: int | None
    checksum_sha256: str | None


class RejectedFile(BaseModel):
    file_name: str
    reason: str


class ToolCallLogEntry(BaseModel):
    tool: str
    status: Literal["ok", "failed"]
    result_count: int | None = None
    error: str | None = None


class GenerationError(BaseModel):
    """Structured failure info — the backend decides how much of
    `message` to show a user; `retryable` is a hint for whether "try
    again" is a reasonable UI action."""

    stage: str  # which pipeline node failed, e.g. "ingest", "generate", "validate"
    error_type: str  # exception class name
    message: str
    retryable: bool = True


class GenerationResult(BaseModel):
    job_id: UUID
    map_id: UUID
    status: Literal["completed", "failed", "rejected"]

    resolved_detail_level: DetailLevel | None = None
    nodes: list[NodeDraft] = Field(default_factory=list)
    edges: list[EdgeDraft] = Field(default_factory=list)
    seed_assets: list[SeedAssetDraft] = Field(default_factory=list)
    rejected_files: list[RejectedFile] = Field(default_factory=list)
    tool_call_log: list[ToolCallLogEntry] = Field(default_factory=list)

    error: GenerationError | None = None


# ---------------------------------------------------------------------
# Chat agent contracts (S2-L8, US-14)
# ---------------------------------------------------------------------


class MapSnapshot(BaseModel):
    """Read-only view of the current map sent to the chat agent.

    The agent NEVER modifies this — it is used only for grounding answers
    and validating node IDs in action proposals.
    """

    map_id: UUID
    nodes: list[NodeDraft] = Field(default_factory=list)
    edges: list[EdgeDraft] = Field(default_factory=list)


class ChatMessage(BaseModel):
    """A single turn in the conversation history."""

    role: Literal["user", "assistant"]
    content: str


class ChatTurnRequest(BaseModel):
    """The payload the backend sends to the chat agent for one turn.

    The namespace for Pinecone retrieval follows the existing convention:
    ``str(map_id)``.  callback_base_url / callback_token are included for
    consistency with GenerationRequest; the ARQ callback layer (S2-L10)
    will use them — the agent itself does not make callback HTTP calls.
    """

    map_id: UUID
    message: str
    history: list[ChatMessage] = Field(default_factory=list)
    summary: str | None = None  # Rolling conversation summary from backend (S2-L9 / US-15)
    map_snapshot: MapSnapshot
    callback_base_url: str
    callback_token: str


class SummarizeRequest(BaseModel):
    """Payload to trigger summarisation of older messages (S2-L9 / US-15)."""

    messages: list[ChatMessage] = Field(default_factory=list)
    previous_summary: str | None = None


class SummarizeResult(BaseModel):
    """Result of a summarisation operation."""

    summary: str
    tokens_estimated: int = 0


class ActionProposal(BaseModel):
    """A proposed change to the map — NEVER applied directly.

    The agent returns this; the user must explicitly confirm before any
    change is applied through a separate flow (S2-L10 / S2-BE3).
    """

    action_type: ChatIntent
    target_node_ids: list[UUID] = Field(default_factory=list)
    parameters: dict[str, Any] = Field(default_factory=dict)
    explanation: str


class ChatTurnResponse(BaseModel):
    """What the chat agent returns for a single conversation turn.

    Exactly one of ``answer`` or ``action_proposal`` is populated, unless
    ``needs_clarification`` is True, in which case both may be None.
    """

    intent: ChatIntent
    answer: str | None = None
    action_proposal: ActionProposal | None = None
    cited_node_ids: list[UUID] = Field(default_factory=list)
    source_refs: list[str] = Field(default_factory=list)
    needs_clarification: bool = False
    clarification_question: str | None = None
