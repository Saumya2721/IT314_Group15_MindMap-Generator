import logging
from typing import Any

from core.config import settings
from core.supabase import admin, anon_client
from fastapi import HTTPException

logger = logging.getLogger(__name__)


class AuthService:
    @staticmethod
    def _check_suspension(user_id: str) -> None:
        """Verify that the user account is not suspended.

        Raises HTTP 403 Forbidden if the user's profile has `suspended_at` set.
        """
        try:
            profile_res = admin.table("profiles").select("suspended_at").eq("id", user_id).execute()
            data = getattr(profile_res, "data", None)
            if isinstance(data, list) and len(data) > 0:
                first = data[0]
                if isinstance(first, dict) and first.get("suspended_at") is not None:
                    logger.warning("Suspended user attempted access: %s", user_id)
                    raise HTTPException(
                        status_code=403,
                        detail="Account is suspended. Please contact support.",
                    )
        except HTTPException:
            raise
        except Exception as exc:
            logger.warning("Could not check suspension status for user %s: %s", user_id, exc)

    @staticmethod
    def signup(email: str, password: str, name: str | None = None) -> dict[str, Any]:
        payload: dict[str, Any] = {"email": email, "password": password}
        if name:
            payload["options"] = {"data": {"name": name, "full_name": name}}
        try:
            res = anon_client().auth.sign_up(payload)  # type: ignore[arg-type]
        except Exception as e:
            raise HTTPException(status_code=400, detail=str(e))
        if res.user is None:
            raise HTTPException(status_code=400, detail="Signup failed")
        return {
            "message": "User registered successfully",
            "user": {"id": res.user.id, "email": res.user.email},
            "email_confirmation_required": res.session is None,
        }

    @staticmethod
    def login(email: str, password: str) -> dict[str, Any]:
        try:
            res = anon_client().auth.sign_in_with_password({"email": email, "password": password})
        except Exception as e:
            logger.warning("Supabase login failed for %s: %s", email, e)
            raise HTTPException(status_code=401, detail="Invalid Email or Password")
        if not res.session or not res.user:
            logger.warning("Supabase sign-in succeeded but returned no session for %s", email)
            raise HTTPException(status_code=401, detail="Invalid Email or Password")
        AuthService._check_suspension(str(res.user.id))
        return {
            "access_token": res.session.access_token,
            "refresh_token": res.session.refresh_token,
            "expires_in": res.session.expires_in,
            "token_type": "bearer",
            "user": {"id": res.user.id, "email": res.user.email},
        }

    @staticmethod
    def get_google_auth_url(redirect_to: str | None = None) -> dict[str, str]:
        target_redirect = redirect_to or f"{settings.FRONTEND_URL}/auth/callback"
        try:
            client = anon_client()
            res = client.auth.sign_in_with_oauth({"provider": "google", "options": {"redirect_to": target_redirect}})
            # Retrieve the PKCE code_verifier generated by supabase_auth for this authorization request
            verifier_key = f"{client.auth._storage_key}-code-verifier"
            code_verifier = client.auth._storage.get_item(verifier_key) or ""
            return {
                "google_auth_url": res.url,
                "code_verifier": code_verifier,
            }
        except Exception as e:
            raise HTTPException(status_code=400, detail=str(e))

    @staticmethod
    def exchange_code_for_session(code: str, code_verifier: str | None = None) -> dict[str, Any]:
        """Exchange OAuth auth code (returned in callback) for user session tokens."""
        try:
            params: dict[str, Any] = {"auth_code": code}
            if code_verifier:
                params["code_verifier"] = code_verifier
            res = anon_client().auth.exchange_code_for_session(params)  # type: ignore[typeddict-item,arg-type]
            if not res or not res.session or not res.user:
                raise HTTPException(status_code=400, detail="Failed to exchange authorization code")
            AuthService._check_suspension(str(res.user.id))
            return {
                "access_token": res.session.access_token,
                "refresh_token": res.session.refresh_token,
                "expires_in": res.session.expires_in,
                "token_type": "bearer",
                "user": {"id": res.user.id, "email": res.user.email},
            }
        except HTTPException:
            raise
        except Exception as e:
            raise HTTPException(status_code=400, detail=f"Google authentication exchange failed: {str(e)}")

    @staticmethod
    def forgot_password(email: str, redirect_to: str | None = None) -> dict[str, Any]:
        """Send password reset email to user."""
        target_redirect = redirect_to or f"{settings.FRONTEND_URL}/reset-password"
        try:
            anon_client().auth.reset_password_for_email(email, options={"redirect_to": target_redirect})
            return {"message": "Password reset instructions sent to your email."}
        except Exception as e:
            raise HTTPException(status_code=400, detail=str(e))

    @staticmethod
    def reset_password(token: str, new_password: str) -> dict[str, Any]:
        """Update password for the authenticated user using token/session."""
        try:
            client = anon_client()
            # Set the current user session using the token to allow updating password
            res = client.auth.get_user(token)
            if not res or not res.user:
                raise HTTPException(status_code=401, detail="Invalid or expired reset token")

            # Use admin client to safely update the user password by ID
            admin.auth.admin.update_user_by_id(str(res.user.id), {"password": new_password})
            return {"message": "Password has been successfully reset. You can now log in."}
        except HTTPException:
            raise
        except Exception as e:
            logger.error("Password reset failed for user %s: %s", getattr(res, "user", None), e, exc_info=True)
            raise HTTPException(status_code=400, detail=f"Password reset failed: {str(e)}")

    @staticmethod
    def refresh_session(refresh_token: str) -> dict[str, Any]:
        """Obtain a new access token using a valid refresh token."""
        try:
            res = anon_client().auth.refresh_session(refresh_token)
            if not res or not res.session or not res.user:
                raise HTTPException(status_code=401, detail="Invalid or expired refresh token")
            AuthService._check_suspension(str(res.user.id))
            return {
                "access_token": res.session.access_token,
                "refresh_token": res.session.refresh_token,
                "expires_in": res.session.expires_in,
                "token_type": "bearer",
                "user": {"id": res.user.id, "email": res.user.email},
            }
        except HTTPException:
            raise
        except Exception:
            raise HTTPException(status_code=401, detail="Could not refresh session")
